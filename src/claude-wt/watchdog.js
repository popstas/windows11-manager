/**
 * Сторож демона claude-wt. Без I/O: статус, диагноз, лечение и часы — снаружи.
 *
 * Переехал из windows-mqtt/src/modules/claude-wt-watchdog.js. Там демон крутился
 * в том же процессе, что и сторож, и лечением был `startClaudeWt()`. Здесь демон
 * — отдельный дочерний процесс под присмотром Rust, поэтому лечение приходит
 * аргументом `remedy` и о себе рассказывает само: поднимать демона отсюда нельзя,
 * два демона на одном состоянии хуже, чем ни одного.
 */

// Полминуты: при пороге молчания в минуту это две проверки на порог, то есть
// поломку замечают быстрее, чем она успевает надоесть, и не чаще, чем нужно.
const CHECK_INTERVAL_MS = 30000;
// Неустранимая поломка не должна превратить лог в поток перезапусков. Диагноз
// при этом пишется каждую проверку — по частоте строк видно, что беда не ушла.
const REMEDY_COOLDOWN_MS = 300000;
// Запасные пороги на случай библиотеки постарше: без них silenceMs/graceMs
// приезжают undefined, сравнения с ними всегда ложны — и сторож либо считает
// демона больным с первой же секунды, либо здоровым всегда. Второе хуже: он
// молча слепнет, а слепой сторож — ровно та беда, от которой он поставлен.
const DEFAULT_SILENCE_MS = 60000;
const DEFAULT_GRACE_MS = 60000;

/**
 * Проверка живости демона.
 *
 * Решение о болезни принимает библиотека (`claudeWtHealth`), здесь только
 * реакция: сказать и позвать лечение. Разделение не косметическое — пороги и
 * смысл «болен» живут там же, где счётчики, а приложение владеет логом и
 * жизненным циклом.
 */
function createClaudeWtWatchdog({
  status,
  health,
  remedy,
  log,
  // Выздоровление — это событие, и знать о нём надо снаружи: неустранимая
  // поломка иначе звала бы человека каждый кулдаун до скончания века, а гасить
  // «уже звали» по своему собственному сроку значило бы завести второй порог
  // рядом с чужим.
  onHealthy = () => {},
  now = Date.now,
  silenceMs = DEFAULT_SILENCE_MS,
  graceMs = DEFAULT_GRACE_MS,
  cooldownMs = REMEDY_COOLDOWN_MS,
}) {
  // -Infinity, а не 0: с нулём первое же лечение после старта процесса попало бы
  // в кулдаун только при подставных часах в тестах, и тест лгал бы.
  let lastRemedyAt = -Infinity;

  return function check() {
    // Тело целиком под перехватом: status() ходит в конфиг и в опубликованный
    // файл окон — оба умеют бросать. Исключение отсюда попадало бы в глушащий
    // обработчик таймера, и сторож замолкал бы ровно так же незаметно, как
    // демон, за которым он смотрит.
    try {
      return runCheck();
    } catch (e) {
      log(`claude-wt: сторож не смог проверить демона: ${e.message}`, 'error');
      return false;
    }
  };

  function runCheck() {
    const s = status();
    const nowMs = now();
    const h = health({
      running: s.running,
      lastTickAt: s.lastTickAt,
      startedAt: s.startedAt,
      nowMs,
      silenceMs,
      graceMs,
    });
    if (h.healthy) {
      onHealthy();
      return false;
    }

    const parts = [`claude-wt: демон нездоров (${h.reason})`];
    // Возраст пишется, только когда он что-то значит: у незапущенного демона
    // последнего тика нет, и «последний тик 0s назад» сбивал бы с толку.
    if (h.ageMs) parts.push(`последний тик ${Math.round(h.ageMs / 1000)}s назад`);
    // Счётчики падений есть только у сторожа в одном процессе с демоном. Через
    // файл окон их не видно, и «падений подряд 0, последняя ошибка: —» в каждой
    // строке был бы не диагнозом, а шумом, который выглядит как диагноз.
    if (s.tickFailures || s.lastTickError) {
      parts.push(`падений подряд ${s.tickFailures}, последняя ошибка: ${s.lastTickError || '—'}`);
    }
    log(parts.join(', '), 'warn');

    if (nowMs - lastRemedyAt < cooldownMs) return false;
    lastRemedyAt = nowMs;
    // О том, что именно сделано, рассказывает само лечение: снять процесс и
    // позвать человека — разные события, и общая строка врала бы про одно из них.
    remedy(s);
    return true;
  }
}

export {
  createClaudeWtWatchdog,
  CHECK_INTERVAL_MS,
  REMEDY_COOLDOWN_MS,
  DEFAULT_SILENCE_MS,
  DEFAULT_GRACE_MS,
};
