/**
 * Секундомер одной просьбы «открой сессию».
 *
 * Цепочка от нажатия в пикере до фокуса проходит через четыре разнородных
 * звена — чтение состояния с сетевого диска, `wt.exe`, `claude -n` на той
 * стороне ssh, автопостановщик с демоном, — и на глаз в ней различимы только
 * два события: окно появилось и окно взяло фокус. Пока не видно, сколько
 * стоит каждое звено, любое сокращение задержек — гадание: срезав не то,
 * получаешь прежние секунды и вдобавок отобранный у человека фокус.
 *
 * Замер постоянный, а не временный на время отладки: пишется он только по
 * действию человека (открытие сессии — единицы раз в час), стоит одну строку
 * на звено, и он же единственный способ заметить, что цепочка снова
 * растянулась — на живой машине с сетевым диском это происходит само.
 *
 * Строка несёт оба числа: `+N` — сколько занял сам шаг, `(M)` — сколько
 * прошло от начала просьбы. Без первого не видно виновника, без второго — не
 * сходится с тем, что человек чувствует.
 */
function startTiming(label, { now = Date.now, log = (m) => console.error(m) } = {}) {
  const t0 = now();
  let prev = t0;
  return function mark(step) {
    const t = now();
    log(`[claude-wt] timing ${label}: ${step} +${t - prev}ms (${t - t0}ms)`);
    prev = t;
    return t - t0;
  };
}

/**
 * Заглушка для тех, кто зовёт то же самое не по просьбе человека.
 *
 * `claudeWtSessions()` читают и пикер, и экспорт в Home Assistant, и тик
 * демона; разбивка по звеньям нужна только в горячем пути открытия, а в
 * остальных вызовах она забила бы журнал. Функция, а не `undefined`, чтобы у
 * зовущего не было ветки «а есть ли секундомер».
 */
const noTiming = () => 0;

export { startTiming, noTiming };
