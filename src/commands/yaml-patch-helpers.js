/**
 * Мелочи, общие всем хирургическим правкам YAML-конфига.
 *
 * Правки конфига здесь делаются не пересборкой документа, а заменой ровно того
 * диапазона символов, который отвечает за нужное значение (почему — см. шапку
 * `tile-zones-patch.js`). Такому приёму нужны две вещи от исходного текста:
 * его перевод строки и фактический отступ строки, на которую он целится. Обе
 * лежат здесь, потому что патчеров стало два — списка зон и одиночного скаляра.
 */

/** Перевод строки исходного файла — угадывается по первому найденному \r\n,
 *  чтобы наши собственные новые строки не сбивали CRLF-файл на LF. */
function detectEol(raw) {
  return raw.includes('\r\n') ? '\r\n' : '\n';
}

/** Отступ (число пробелов) строки, на которой лежит символ `offset`. */
function indentAt(text, offset) {
  const lineStart = text.lastIndexOf('\n', offset - 1) + 1;
  let i = lineStart;
  while (i < offset && text[i] === ' ') i++;
  return i - lineStart;
}

/** Перевести наши собственные `\n` в перевод строки исходного файла. */
function eolConverter(eol) {
  return (s) => (eol === '\n' ? s : s.replace(/\n/g, eol));
}

export { detectEol, indentAt, eolConverter };
